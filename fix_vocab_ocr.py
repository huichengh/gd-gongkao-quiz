def main():
    items = json.loads(P.read_text(encoding="utf-8"))
    before = len(items)
    out, dropped, renamed = [], 0, 0

    for it in items:
        w = (it.get("w") or "").strip()
        if "删除" in w or "修改" in w:          # 占位符
            dropped += 1
            continue
        if w in FIX_W:
            nw, nd = FIX_W[w]
            it["w"] = nw
            if nd:
                it["d"] = nd
            renamed += 1
        elif w in FIX_CHAR:
            it["w"] = FIX_CHAR[w]
            renamed += 1
        elif w in FIX4:
            nw, nd = FIX4[w]
            if nw:                      # None 表示词条没错，只改释义
                it["w"] = nw
            if nd:
                it["d"] = nd
            renamed += 1
        if it["w"] == "源远流长":
            it["d"] = it["d"].replace("高频成语积累800词记忆版解释", "")
        out.append(it)

    # 改完可能有两条撞成同一个词（「以邻为」和「以邻为垦」都变「以邻为壑」），
    # 保留释义更长的那条
    best = {}
    for it in out:
        w = it["w"]
        if w not in best or len(it.get("d") or "") > len(best[w].get("d") or ""):
            best[w] = it
    dedup = len(out) - len(best)
    out = list(best.values())

    P.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{before} → {len(out)}  （去掉占位符 {dropped}，修正词条 {renamed}，"
          f"合并重复 {dedup}）")


if __name__ == "__main__":
    main()
