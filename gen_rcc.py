def build_items() -> list[dict]:
    """校验并返回题库条目；供 gen_math.py 合并。"""
    items = []
    for (qid, tag, lv, stem, opts, ans, exp, expect, solver) in D:
        got = solver()
        assert abs(float(got) - float(expect)) < 1e-9, (
            f"{qid} 答案对不上：算式={float(got)} 标注={float(expect)}")
        assert len(opts) == 4 and len(set(opts)) == 4, f"{qid} 选项数或重复有问题"
        assert 0 <= ans < 4, f"{qid} 正确项下标越界"
        flat = opts[ans].replace(" ", "")
        cands = [str(expect), str(int(expect))] if float(expect).is_integer() else [str(expect)]
        assert any(c in flat for c in cands), f"{qid} 正确项文字里找不到 {expect}（选项：{opts[ans]}）"
        items.append({"id": qid, "tag": tag, "lv": lv, "t": stem,
                      "opts": list(opts), "ans": ans, "exp": exp,
                      "cat": "集合容斥"})
    return items


