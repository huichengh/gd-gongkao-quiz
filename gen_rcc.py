def two(a: int, b: int, both: int) -> dict:
    """两集合：a、b 是两边的数量，both 是交集。返回各区域。"""
    assert both <= min(a, b), f"交集 {both} 超过较小的集合"
    return {"a_only": a - both, "b_only": b - both, "either": a + b - both}


def three(a: int, b: int, c: int, ab: int, ac: int, bc: int, abc: int) -> dict:
    """三集合标准型。返回七个区域与「至少一项」。"""
    r = {
        "a_only": a - ab - ac + abc,
        "b_only": b - ab - bc + abc,
        "c_only": c - ac - bc + abc,
        "ab_only": ab - abc,
        "ac_only": ac - abc,
        "bc_only": bc - abc,
        "abc": abc,
    }
    for k, v in r.items():
        assert v >= 0, f"区域 {k} 算出负数 {v}，题目数据矛盾"
    r["either"] = a + b + c - ab - ac - bc + abc
    r["exactly_one"] = r["a_only"] + r["b_only"] + r["c_only"]
    r["exactly_two"] = r["ab_only"] + r["ac_only"] + r["bc_only"]
    r["two_or_more"] = r["exactly_two"] + abc
    return r


