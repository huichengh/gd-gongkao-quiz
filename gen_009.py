def scatter(items):
    need = {i: len(items) // 4 for i in range(4)}
    out = []
    for s, o, a, k, e in items:
        if need[a] > 0:
            need[a] -= 1
            out.append((s, o, a, k, e))
        else:
            tgt = next(i for i in range(4) if need[i] > 0)
            need[tgt] -= 1
            new = list(o)
            new[a], new[tgt] = new[tgt], new[a]
            out.append((s, new, tgt, k, e))
    return out


